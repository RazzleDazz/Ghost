with open("autonomous_bridge.py", "w") as f:
    f.write("import os, urllib.request, json, subprocess\n")
with open("autonomous_bridge.py", "a") as f:
    f.write("API_KEY = os.environ.get('GEMINI_API_KEY')\n")
    f.write("URL = f'https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={API_KEY}'\n")
with open("autonomous_bridge.py", "a") as f:
    f.write("def execute_bridge():\n")
    f.write("    if not API_KEY:\n")
    f.write("        print('[-] Error: GEMINI_API_KEY not set.')\n")
    f.write("        return\n")
    f.write("    payload = {'contents': [{'parts': [{'text': 'Return ONLY a raw JSON object with a single key command containing a safe bash command like uptime or none.'}]}]}\n")
with open("autonomous_bridge.py", "a") as f:
    f.write("    req = urllib.request.Request(URL, data=json.dumps(payload).encode('utf-8'), headers={'Content-Type': 'application/json'}, method='POST')\n")
    f.write("    try:\n")
    f.write("        with urllib.request.urlopen(req) as resp:\n")
    f.write("            res = json.loads(resp.read().decode('utf-8'))\n")
    f.write("            raw = res['candidates'][0]['content']['parts'][0]['text'].strip()\n")
    f.write("            if raw.startswith('```'):\n")
    f.write("                raw = raw.split('```')[1]\n")
    f.write("                if raw.startswith('json'): raw = raw[4:]\n")
    f.write("            raw = raw.strip()\n")
    f.write("            cmd = json.loads(raw).get('command', 'none')\n")
    f.write("            print(f'[+] Received command: {cmd}')\n")
    f.write("            if cmd and cmd != 'none':\n")
    f.write("                out = subprocess.check_output(cmd, shell=True, stderr=subprocess.STDOUT).decode('utf-8')\n")
    f.write("                print(f'[+] Output:\\n{out.strip()}')\n")
    f.write("            else:\n")
    f.write("                print('[+] No remote action required.')\n")
    f.write("    except Exception as e:\n")
    f.write("        print(f'[-] Execution failed: {e}')\n")
    f.write("if __name__ == '__main__':\n")
    f.write("    execute_bridge()\n")
